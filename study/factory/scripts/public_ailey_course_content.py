def quiz_paragraph(context: LessonContext, guides: tuple[KnowledgeGuide, ...]) -> str:
    sentences = [
        _sentence(f"{context.title} 확인 문제는 공식 토픽별 정의와 절차 및 검증근거를 실제 답안으로 회수한다"),
        _sentence(f"{context.title} 답안은 {_basis(context)}의 범위와 {_sources(context)}의 기준일을 따른다"),
    ]
    for index, (topic, guide) in enumerate(zip(context.topics, guides), start=1):
        sentences.extend((
            _sentence(f"{context.title} 확인 문제 {index}: ‘{topic}’에서 {guide.question}", True),
            _sentence(f"{context.title} 정답 {index}: {guide.answer}"),
            _sentence(f"{context.title} 해설 {index}: {guide.explanation}"),
        ))
    review = SAFETY_REVIEW if context.course_id.startswith("industrial-safety") else QUALITY_REVIEW
    index = 0
    while len(sentences) < 15:
        sentences.append(_sentence(f"{context.title} 복기 {index + 1}에서는 {review[index % len(review)]}"))
        index += 1
    if len(sentences) != 15:
        raise ValueError(f"{context.course_id}:{context.lesson_id}: quiz density overflow")
    return " ".join(sentences)


def summary_paragraph(context: LessonContext, guides: tuple[KnowledgeGuide, ...]) -> str:
    sentences = [
        _sentence(f"{context.title} 요약의 공식범위 경로는 다음과 같다: {_basis(context)}"),
        _sentence(f"{context.title} 요약은 정의에서 원리와 절차 및 예시와 경계와 검증으로 이어진다"),
    ]
    for index, (topic, guide) in enumerate(zip(context.topics, guides), start=1):
        sentences.append(_sentence(f"{context.title} 요약 토픽 {index}인 ‘{topic}’의 핵심정의는 {guide.definition}"))
        detail = f"계산식은 {guide.formula}이고 {guide.variables}" if guide.formula else f"적용원리는 {guide.principle}"
        sentences.append(_sentence(f"{context.title} 요약 토픽 {index}의 {detail}"))
    facts = []
    for guide in _unique(guides):
        facts.extend((
            f"출발절차는 {guide.procedure[0]}",
            f"실행절차는 {guide.procedure[1]}",
            f"검증절차는 {guide.procedure[2]}",
            f"경계조건은 {guide.boundary}",
            f"최종확인은 {guide.validation}",
        ))
    index = 0
    while len(sentences) < 14:
        sentences.append(_sentence(f"{context.title} 요약점검 {index + 1}에서 {facts[index % len(facts)]}"))
        index += 1
    sentences.append(_sentence(f"{context.title} 학습은 공식출처와 조건을 밝히고 결과를 다시 검증할 때 완성된다"))
    assert len(sentences) == 15
    return " ".join(sentences)


def _intro(context: LessonContext) -> list[str]:
    lines = [
        f"# {context.lesson_id}. {context.raw_title}", "",
        "> **공식 토픽 원문**: " + " · ".join(f"`{topic}`" for topic in _unique(context.raw_topics)), "",
        "> **학습용 정규화 표기**: " + " · ".join(f"`{topic}`" for topic in context.topics), "",
        "> **공식 위치 원문**: " + _basis(context, raw=True), "",
        "> **학습용 경로**: " + _basis(context), "",
    ]
    if context.corrections:
        changes = " · ".join(f"`{raw}` → `{fixed}`" for raw, fixed in context.corrections)
        lines.extend((
            "> **원문 오탈자 정정**: coverage에는 Q-Net 전사 원문을 보존하고 학습 설명에서는 " + changes + " 형태로 바로잡았습니다.", "",
        ))
    if context.duplicate_topics:
        duplicates = " · ".join(f"`{topic}`" for topic in context.duplicate_topics)
        reason = context.duplicate_reason or "같은 원문 항목이 반복되어 학습 설명에서 한 항목으로 통합함"
        lines.extend((
            f"> **중복 통합 주석**: coverage 원문은 보존하고 {duplicates} 항목은 한 번만 설명합니다. 사유: {reason}.", "",
        ))
    for index, (ref, source) in enumerate(zip(context.source_refs, context.sources), start=1):
        title = str(source.get("title", source.get("id", "공식 출처")))
        url = str(source.get("url", ""))
        authority = str(source.get("authority", "발행기관 미기록"))
        retrieved = str(source.get("retrieved_at", "확인일 미기록"))
        start = source.get("effective_from") or "시작일 미기록"
        end = source.get("effective_to") or "종료일 없음 또는 미기록"
        lines.extend((
            f"> **공식 출처 {index}**: `{ref}` · [{title}]({url}) · {authority} · 확인일 {retrieved} · 적용 {start}부터 {end}까지.", "",
        ))
        note = str(source.get("note", "")).strip()
        if note:
            lines.extend((f"> **출처 메모 {index}**: {note}", ""))
    if context.revalidation:
        revalidation_text = " · ".join(
            f"{key}={value}" for key, value in context.revalidation.items()
        )
        lines.extend((f"> **재검증 메타**: {revalidation_text}", ""))
    lines.extend((
        f"> **프롬프트와 라이선스**: pinned Ailey profile `{FF_PROFILE}` · commit `{AILEY_COMMIT}` · 원작자 {ORIGINAL_CREATOR} · adapted by {ADAPTER} · [{LICENSE_NAME}]({LICENSE_URL}).", "",
        f"> **생성 경로**: FF는 `{FF_RENDERER_PATH}`의 결정적 교육 렌더러로 작성했고 CC는 raw upstream 명령 출력이 아니라 `{CC_RENDERER_PATH}`의 deterministic compatibility renderer로 안전 변환합니다.", "",
    ))
    return lines


def render_ff(course_id: str, curriculum: dict, lesson: dict) -> str:
    context = build_lesson_context(course_id, curriculum, lesson)
    guides = guides_for_context(context)
    lines = _intro(context)
    for framework_index, (emoji, title, stages) in enumerate(FRAMEWORKS):
        dynamic = title
        if framework_index == 1:
            dynamic = f"공식 범위와 근거: {context.section_title}"
        elif framework_index == 2:
            dynamic = f"절차와 계산 적용: {context.group_title}"
        elif framework_index == 3:
            dynamic = f"시험 판별과 검증: {context.topics[-1]}"
        lines.extend((f"## {emoji} {dynamic}", ""))
        for local_index, stage in enumerate(stages):
            focus_index = (framework_index + local_index) % len(context.topics)
            if stage.h3_emoji == "❓":
                paragraph = quiz_paragraph(context, guides)
            elif stage.h3_emoji == "✅":
                paragraph = summary_paragraph(context, guides)
            else:
                paragraph = standard_paragraph(context, stage, context.topics[focus_index], guides[focus_index])
            lines.extend((f"### {stage.h3_emoji} {stage.h3_title}", "", paragraph, ""))
    return "\n".join(lines).rstrip() + "\n"


SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?。！？])\s+")
H3_RE = re.compile(r"^###\s+")
HEADING_RE = re.compile(r"^#{1,6}\s+")


def extract_h3_paragraphs(source: str) -> list[str]:
    lines = source.splitlines()
    paragraphs = []
    for line_index, line in enumerate(lines):
        if not H3_RE.match(line):
            continue
        index = line_index + 1
        while index < len(lines) and not lines[index].strip():
            index += 1
        body = []
        while index < len(lines) and lines[index].strip() and not HEADING_RE.match(lines[index]):
            body.append(lines[index].strip())
            index += 1
        paragraphs.append(" ".join(body))
    return paragraphs


def extract_h3_sentences(source: str) -> list[str]:
    return [
        sentence.strip()
        for paragraph in extract_h3_paragraphs(source)
        for sentence in SENTENCE_SPLIT_RE.split(paragraph)
        if sentence.strip()
    ]


def lesson_knowledge_facts(context: LessonContext) -> list[str]:
    """Return the guide and official-context facts assigned to one lesson."""
    facts = []
    for guide in guides_for_context(context):
        facts.extend(fact for _label, fact in guide_fact_slots(guide))
    facts.extend((_basis(context), _sources(context)))
    return [fact for fact in _unique(facts) if fact]


def teaching_focus_assignments(
    context: LessonContext,
) -> list[tuple[Stage, str, KnowledgeGuide]]:
    guides = guides_for_context(context)
    assignments = []
    for framework_index, (_emoji, _title, stages) in enumerate(FRAMEWORKS):
        for local_index, stage in enumerate(stages):
            if stage.h3_emoji in {"❓", "✅"}:
                continue
            focus_index = (framework_index + local_index) % len(context.topics)
            assignments.append((
                stage,
                context.topics[focus_index],
                guides[focus_index],
            ))
    return assignments


def knowledge_bearing_sentences(
    context: LessonContext,
    source: str,
) -> list[str]:
    """Return sentences carrying curriculum knowledge rather than scaffolding."""
    facts = lesson_knowledge_facts(context)
    return [
        sentence
        for sentence in extract_h3_sentences(source)
        if any(fact in sentence for fact in facts)
    ]


def teaching_h3_fact_counts(
    context: LessonContext,
    source: str,
) -> list[int]:
    """Count lesson facts in each of the thirteen non-quiz teaching H3s."""
    counts = []
    paragraphs = extract_h3_paragraphs(source)[:13]
    assignments = teaching_focus_assignments(context)
    for paragraph, (_stage, _focus, guide) in zip(paragraphs, assignments):
        facts = [fact for _label, fact in guide_fact_slots(guide) if fact]
        sentences = [
            sentence.strip()
            for sentence in SENTENCE_SPLIT_RE.split(paragraph)
            if sentence.strip()
        ]
        counts.append(sum(
            any(fact in sentence for fact in facts)
            for sentence in sentences
        ))
    return counts


def semantic_sentence(
    sentence: str,
    context: LessonContext | None = None,
    canonical_facts: list[str] | None = None,
) -> str:
    """Remove cosmetic anchors before measuring substantive repetition."""
    if context is not None:
        facts = canonical_facts or lesson_knowledge_facts(context)
        for fact in sorted(facts, key=len, reverse=True):
            sentence = sentence.replace(fact, "<canonical-fact>")
        # The renderer's action target is a compact compound of official topic
        # nouns and an observable action.  Keep those nouns: masking substrings
        # such as ``수요예측`` inside that compound would make unrelated
        # lessons look identical.  Quoted literal topics are normalized below,
        # while guide facts remain masked above so the comparison still detects
        # repeated carrier prose rather than merely matching canonical facts.
    value = re.sub(r"‘[^’]+’", "<topic>", sentence)
    value = re.sub(
        r"(?:출발점과 정의|구성 요소와 관계|경계와 판단 기준|출제기준의 맥락|"
        r"입력과 결과의 연결|근거 확인 절차|적용 순서|구체 예시와 계산|"
        r"오류와 예방|출제 포인트|비교와 판별|검증 루프|통합 적용)",
        "<stage>",
        value,
    )
    value = re.sub(r"\b\d+-\d+-\d+-\d+\b", "<lesson>", value)
    value = re.sub(r"^<stage> 단계의 목표는 토픽 <topic> 중심으로 ", "", value)
    return " ".join(value.split())


def repeated_ngram_rate(
    sentences: list[str],
    width: int = 5,
    context: LessonContext | None = None,
) -> float:
    ngrams = []
    canonical_facts = lesson_knowledge_facts(context) if context else None
    for sentence in sentences:
        words = semantic_sentence(
            sentence,
            context,
            canonical_facts,
        ).split()
        ngrams.extend(tuple(words[index:index + width]) for index in range(len(words) - width + 1))
    if not ngrams:
        return 0.0
    counts = Counter(ngrams)
    return sum(count - 1 for count in counts.values() if count > 1) / len(ngrams)


def sample_audit_metrics(
    rendered: dict[str, str],
    contexts: dict[str, LessonContext] | None = None,
) -> dict[str, object]:
    documents = {}
    sentence_sets = {}
    for key, source in rendered.items():
        sentences = extract_h3_sentences(source)
        # Quiz and summary intentionally retrieve previously learned facts.
        # Their substantive completeness is checked separately below, so the
        # semantic repetition metric measures the thirteen teaching H3s.
        body_sentences = sentences[:-30] if len(sentences) >= 30 else sentences
        context = (contexts or {}).get(key)
        canonical_facts = lesson_knowledge_facts(context) if context else None
        unique_count = len(set(sentences))
        semantic = [
            semantic_sentence(sentence, context, canonical_facts)
            for sentence in body_sentences
        ]
        semantic_unique = len(set(semantic))
        sentence_sets[key] = set(semantic if context else body_sentences)
        documents[key] = {
            "sentence_count": len(sentences),
            "unique_sentence_count": unique_count,
            "duplicate_rate": 0.0 if not sentences else 1 - unique_count / len(sentences),
            "semantic_duplicate_rate": 0.0 if not semantic else 1 - semantic_unique / len(semantic),
            "repeated_5gram_rate": repeated_ngram_rate(body_sentences, context=context),
        }
    pairs = {
        f"{left}|{right}": len(sentence_sets[left] & sentence_sets[right])
        for left_index, left in enumerate(sentence_sets)
        for right in list(sentence_sets)[left_index + 1:]
    }
    return {
        "documents": documents,
        "pairwise_common_sentences": pairs,
        "max_pairwise_common_sentences": max(pairs.values(), default=0),
    }


