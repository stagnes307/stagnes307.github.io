def public_ailey_content_quality_errors(
    course_id: str,
    curriculum: dict,
    lesson: dict,
    source: str,
    peer_sources: dict[str, str] | None = None,
) -> list[str]:
    """Pure reusable content gate for generated and already-published FFs."""
    errors = ailey_public_ff_quality_errors(
        source,
        lesson["topics"],
        lesson_id=lesson["id"],
        lesson_title=lesson["title"],
    )
    context = build_lesson_context(course_id, curriculum, lesson)
    guides = guides_for_context(context)
    sentences = extract_h3_sentences(source)
    fact_counts = teaching_h3_fact_counts(context, source)
    if len(fact_counts) != 13:
        errors.append(
            f"expected thirteen teaching H3 paragraphs, found {len(fact_counts)}"
        )
    else:
        empty_h3 = [
            index
            for index, count in enumerate(fact_counts, start=1)
            if count < 8
        ]
        if empty_h3:
            errors.append(
                "teaching H3 has fewer than eight current-guide facts: "
                + ", ".join(map(str, empty_h3))
            )
    duplicate_rate = 0.0 if not sentences else 1 - len(set(sentences)) / len(sentences)
    if duplicate_rate > 0.02:
        errors.append(f"exact sentence duplicate rate exceeds 2 percent: {duplicate_rate:.4f}")
    body_sentences = sentences[:-30] if len(sentences) >= 30 else sentences
    canonical_facts = lesson_knowledge_facts(context)
    semantic = [
        semantic_sentence(sentence, context, canonical_facts)
        for sentence in body_sentences
    ]
    semantic_rate = 0.0 if not semantic else 1 - len(set(semantic)) / len(semantic)
    if semantic_rate > 0.05:
        errors.append(f"anchor-stripped sentence duplicate rate exceeds 5 percent: {semantic_rate:.4f}")
    ngram_rate = repeated_ngram_rate(body_sentences, context=context)
    if ngram_rate > 0.18:
        errors.append(f"repeated semantic 5-gram rate exceeds 18 percent: {ngram_rate:.4f}")
    forbidden = QUALITY_CONTAMINATION if course_id.startswith("quality-management") else SAFETY_CONTAMINATION
    for phrase in forbidden:
        if phrase in source:
            errors.append(f"cross-domain contamination: {phrase}")
    for pattern in BROKEN_KOREAN:
        if pattern.search(source):
            errors.append(f"broken Korean particle pattern: {pattern.pattern}")
    h3_text = " ".join(extract_h3_paragraphs(source))
    for topic in lesson["topics"]:
        if re.search(r"[.!?。！？]+(?=\s)", topic) and topic in h3_text:
            errors.append(f"raw topic punctuation leaked into H3 paragraph: {topic}")

    calculation_required = lesson.get("lesson_type") == "calculation" or any(guide.formula for guide in guides)
    if calculation_required:
        if not any(guide.formula and guide.formula in source for guide in guides):
            errors.append("calculation lesson lacks its canonical formula")
        if not re.search(r"\d+(?:\.\d+)?", h3_text):
            errors.append("calculation lesson lacks a numeric worked example")
        if not any(unit in h3_text for unit in (
            "단위", "밀리미터", "퍼센트", "체적퍼센트", "시간", "볼트", "암페어", "줄", "세제곱미터", "킬로뉴턴",
        )):
            errors.append("calculation lesson lacks variable units")

    required_attribution = (FF_PROFILE, AILEY_COMMIT, ORIGINAL_CREATOR, ADAPTER, LICENSE_NAME, CC_RENDERER_PATH)
    for token in required_attribution:
        if token not in source:
            errors.append(f"missing provenance or attribution token: {token}")
    for ref, record in zip(context.source_refs, context.sources):
        for value in (ref, record.get("title"), record.get("url"), record.get("retrieved_at"), record.get("note")):
            if value and str(value) not in source:
                errors.append(f"missing source provenance value: {value}")
    for key, value in context.revalidation.items():
        if str(key) not in source or str(value) not in source:
            errors.append(f"missing revalidation provenance: {key}={value}")
    for raw, fixed in context.corrections:
        if raw not in source or fixed not in source:
            errors.append(f"missing correction provenance: {raw} -> {fixed}")
    if context.duplicate_topics and context.duplicate_reason not in source:
        errors.append("missing duplicate-topic provenance reason")

    quiz = extract_h3_paragraphs(source)[-2] if len(extract_h3_paragraphs(source)) >= 2 else ""
    for index, (topic, guide) in enumerate(zip(context.topics, guides), start=1):
        for token in (f"확인 문제 {index}", f"정답 {index}", f"해설 {index}", topic, guide.answer, guide.explanation):
            if token not in quiz:
                errors.append(f"topic quiz lacks substantive token: {token}")

    if peer_sources:
        current = set(knowledge_bearing_sentences(context, source))
        for peer_id, peer_source in peer_sources.items():
            if peer_id == lesson["id"]:
                continue
            common = len(current & set(extract_h3_sentences(peer_source)))
            if common > 3:
                errors.append(f"shares {common} exact sentences with {peer_id}")
    return list(dict.fromkeys(errors))


def corpus_content_quality_errors(
    course_id: str,
    curriculum: dict,
    rendered: dict[str, str],
    *,
    include_lesson_errors: bool = True,
) -> list[str]:
    """Apply the pure content gate to every leaf in one curriculum."""
    errors = []
    lessons = {
        sublesson["id"]: {
            **sublesson,
            "section_id": section["id"],
            "section_title": section["title"],
            "unit_id": unit["id"],
            "unit_title": unit["title"],
            "lesson_group_id": group["id"],
            "lesson_group_title": group["title"],
        }
        for section in curriculum["sections"]
        for unit in section["units"]
        for group in unit["lessons"]
        for sublesson in group["sublessons"]
    }
    sentence_sets = {}
    for lesson_id, source in rendered.items():
        if lesson_id not in lessons:
            continue
        context = build_lesson_context(
            course_id,
            curriculum,
            lessons[lesson_id],
        )
        sentences = extract_h3_sentences(source)
        body_sentences = sentences[:-30] if len(sentences) >= 30 else sentences
        canonical_facts = lesson_knowledge_facts(context)
        sentence_sets[lesson_id] = {
            semantic_sentence(sentence, context, canonical_facts)
            for sentence in body_sentences
        }
    if include_lesson_errors:
        for lesson_id, lesson in lessons.items():
            source = rendered.get(lesson_id)
            if source is None:
                errors.append(f"{course_id}:{lesson_id}: missing rendered FF")
                continue
            for error in public_ailey_content_quality_errors(
                course_id, curriculum, lesson, source,
            ):
                errors.append(f"{course_id}:{lesson_id}: {error}")
    lesson_ids = list(sentence_sets)
    for left_index, left in enumerate(lesson_ids):
        for right in lesson_ids[left_index + 1:]:
            common = len(sentence_sets[left] & sentence_sets[right])
            if common > 3:
                errors.append(f"{course_id}:{left}|{right}: share {common} exact sentences")
    return errors
