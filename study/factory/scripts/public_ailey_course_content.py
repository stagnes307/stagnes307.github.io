@dataclass(frozen=True)
class LessonContext:
    course_id: str
    course_title: str
    mode: str
    lesson_type: str
    lesson_id: str
    raw_title: str
    title: str
    section_title: str
    unit_title: str
    group_title: str
    raw_topics: tuple[str, ...]
    topics: tuple[str, ...]
    duplicate_topics: tuple[str, ...]
    corrections: tuple[tuple[str, str], ...]
    duplicate_reason: str
    official_basis: tuple[str, ...]
    normalized_official_basis: tuple[str, ...]
    source_refs: tuple[str, ...]
    sources: tuple[dict, ...]
    revalidation: dict

    @property
    def classification_text(self) -> str:
        """Expose the full official context used for classification."""
        source_text = " ".join(
            " ".join(str(source.get(key, "")) for key in (
                "id", "title", "authority", "url", "note",
            ))
            for source in self.sources
        )
        return " ".join((
            self.section_title,
            self.unit_title,
            self.group_title,
            self.title,
            " ".join(self.topics),
            " ".join(self.normalized_official_basis),
            " ".join(self.source_refs),
            source_text,
        )).lower()


