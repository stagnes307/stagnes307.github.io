def _prepare_stage_clauses(
    context: LessonContext,
    stage: Stage,
    focus: str,
    guide: KnowledgeGuide,
    clauses: list[str],
    formula: str,
    variables: str,
) -> list[str]:
    facts = (
        ("definition", guide.definition),
        ("principle", guide.principle),
        ("inputs", guide.inputs),
        ("procedure_1", guide.procedure[0]),
        ("procedure_2", guide.procedure[1]),
        ("procedure_3", guide.procedure[2]),
        ("example_1", guide.example[0]),
        ("example_2", guide.example[1]),
        ("boundary", guide.boundary),
        ("validation", guide.validation),
        ("question", guide.question),
        ("answer", guide.answer),
        ("explanation", guide.explanation),
        ("formula", formula),
        ("variables", variables),
        ("sources", _sources(context)),
        ("basis", _basis(context)),
    )
    prepared = []
    for clause in clauses:
        replacement = None
        home_fact = False
        for label, fact in facts:
            if fact and fact in clause:
                if FACT_STAGE[label] != stage.h3_emoji:
                    replacement = _stage_fact_replacement(context, stage, focus, label)
                    break
                home_fact = True
        value = replacement or clause
        # Repeated ``토픽 ‘...’`` labels belong only in the paragraph's
        # opening sentence.  Later sentences start from the fact or operation.
        replacement_subject = focus if home_fact else "해당 개념"
        value = value.replace(f"토픽 ‘{focus}’", replacement_subject)
        value = value.replace(f"‘{focus}’", replacement_subject)
        if home_fact and focus not in value:
            value = f"{context.group_title}에서 다루는 {focus}의 {value}"
        prepared.append(value)
    return prepared


