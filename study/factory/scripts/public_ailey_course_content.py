def _unique(values: Iterable[str]) -> list[str]:
    return list(dict.fromkeys(values))


def _apply_learning_replacements(
    value: str,
    corrections: dict[str, str] | None = None,
) -> str:
    normalized = value
    replacements = list((corrections or {}).items()) + list(FALLBACK_NORMALIZATION)
    for original, replacement in replacements:
        if original == "인체의 저":
            if normalized.strip() == original:
                normalized = replacement
        else:
            normalized = normalized.replace(original, replacement)
    return normalized


def normalize_learning_text(
    value: str,
    corrections: dict[str, str] | None = None,
) -> str:
    normalized = _apply_learning_replacements(value, corrections)
    # A criterion can contain multiple sentences.  Convert only punctuation at
    # an actual whitespace/end boundary into a visible label separator.  This
    # preserves decimals and compact abbreviations such as F.T.A.
    normalized = re.sub(r"[.!?。！？]+(?=\s|$)", " / ", normalized)
    normalized = re.sub(r"(?:\s*/\s*){2,}", " / ", normalized)
    return " ".join(normalized.split()).strip(" /·")


def build_lesson_context(
    course_id: str,
    curriculum: dict,
    lesson: dict,
) -> LessonContext:
    source_index = {
        source["id"]: source
        for source in curriculum.get("sources", [])
        if isinstance(source, dict) and isinstance(source.get("id"), str)
    }
    missing = [ref for ref in lesson.get("source_refs", []) if ref not in source_index]
    if missing:
        raise ValueError(f"{course_id}:{lesson['id']}: unresolved source refs {missing}")

    explicit = lesson.get("topic_corrections", {})
    if not isinstance(explicit, dict):
        raise ValueError(f"{course_id}:{lesson['id']}: topic_corrections must be an object")
    raw_topics = tuple(lesson["topics"])
    normalized_all = [normalize_learning_text(topic, explicit) for topic in raw_topics]
    counts = Counter(normalized_all)
    topics = tuple(_unique(normalized_all))
    correction_pairs = []
    for raw in raw_topics:
        corrected = _apply_learning_replacements(raw, explicit)
        if corrected != raw:
            correction_pairs.append((raw, corrected))
    corrections = tuple(_unique(correction_pairs))
    raw_basis = tuple(str(item) for item in lesson.get("official_basis", []))
    return LessonContext(
        course_id=course_id,
        course_title=curriculum["title"],
        mode=curriculum.get("mode", ""),
        lesson_type=str(lesson.get("lesson_type", "concept")),
        lesson_id=lesson["id"],
        raw_title=lesson["title"],
        title=normalize_learning_text(lesson["title"], explicit),
        section_title=normalize_learning_text(lesson["section_title"], explicit),
        unit_title=normalize_learning_text(lesson["unit_title"], explicit),
        group_title=normalize_learning_text(lesson["lesson_group_title"], explicit),
        raw_topics=raw_topics,
        topics=topics,
        duplicate_topics=tuple(topic for topic, count in counts.items() if count > 1),
        corrections=corrections,
        duplicate_reason=str(lesson.get("duplicate_topic_reason", "")).strip(),
        official_basis=raw_basis,
        normalized_official_basis=tuple(
            normalize_learning_text(item, explicit) for item in raw_basis
        ),
        source_refs=tuple(lesson.get("source_refs", [])),
        sources=tuple(source_index[ref] for ref in lesson.get("source_refs", [])),
        revalidation=dict(curriculum.get("revalidation", {})),
    )


