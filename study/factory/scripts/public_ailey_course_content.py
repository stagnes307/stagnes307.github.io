def action_profile_for(context: LessonContext, focus: str) -> ActionProfile:
    """Classify the official atom by its observable learning action."""
    text = " ".join((focus, context.title, context.group_title)).lower()
    ranked = []
    for priority, profile in enumerate(ACTION_PROFILES):
        matches = [marker for marker in profile.markers if marker.lower() in text]
        ranked.append((
            sum(10 + len(marker) for marker in matches),
            max((len(marker) for marker in matches), default=0),
            -priority,
            profile,
        ))
    score, _length, _priority, profile = max(ranked, key=lambda item: item[:3])
    if score:
        return profile
    fallback = {
        "calculation": "analyze",
        "analysis": "analyze",
        "interpretation": "analyze",
        "comparison": "decide",
        "exam-strategy": "decide",
        "coding": "execute",
        "data-handling": "execute",
        "sql": "execute",
        "implementation": "execute",
        "debugging": "verify",
    }.get(context.lesson_type, "establish")
    return next(item for item in ACTION_PROFILES if item.code == fallback)


def _target_terms(value: str, profile: ActionProfile) -> list[str]:
    reduced = value
    all_markers = sorted(
        {marker for item in ACTION_PROFILES for marker in item.markers},
        key=len,
        reverse=True,
    )
    for marker in all_markers:
        reduced = reduced.replace(marker, " ")
    tokens = []
    for raw_token in re.findall(r"[가-힣A-Za-z0-9]+", reduced):
        token = raw_token
        for suffix in ("으로", "에서", "에게", "부터", "까지", "보다", "처럼", "으로", "로", "을", "를", "이", "가", "은", "는", "의", "에"):
            if len(token) > len(suffix) + 1 and token.endswith(suffix):
                token = token[:-len(suffix)]
                break
        if len(token) >= 2 and token not in {
            "개요", "개념", "기초", "방법", "종류", "사항", "일반", "따라",
            "대한", "위한", "통해", "있는", "있도록", "있다", "정해진",
            "설정된", "필요한", "각", "하도록", "지원할", "하기", "결과에",
            "관련법령", "기준", "지침", "인해", "발생할", "발생하는", "위해",
            "관한", "통한", "수있다", "할수", "합격한", "하여", "준수하여",
            "활용하여", "제공할", "작성할", "설치할", "확인할", "파악할",
        }:
            tokens.append(token)
    return _unique(tokens)


def topic_action_target(
    context: LessonContext,
    focus: str,
    guide: KnowledgeGuide,
    profile: ActionProfile,
) -> str:
    """Derive a meaningful object phrase, not a cosmetic lesson identifier."""
    section_terms = _target_terms(context.section_title, profile)
    unit_terms = _target_terms(context.unit_title, profile)
    group_terms = _target_terms(context.group_title, profile)
    lesson_terms = _target_terms(context.title, profile)
    focus_terms = _target_terms(focus, profile)
    matching_keywords = [
        keyword
        for keyword in guide.keywords
        if _keyword_matches(focus, keyword) and keyword.lower() != focus.lower()
    ]
    scope_terms = _unique((*section_terms[:1], *unit_terms[:1], *group_terms[:1]))
    reserved = {
        value.lower()
        for value in (*scope_terms, *matching_keywords)
    }
    distinctive = [
        value for value in focus_terms
        if value.lower() not in reserved
    ]
    terms = [
        *scope_terms,
        *distinctive[:2],
        *distinctive[-1:],
        *lesson_terms[-1:],
        *sorted(matching_keywords, key=len, reverse=True)[:1],
    ]
    if not terms:
        terms.extend(keyword for keyword in guide.keywords[:2] if keyword)
    if not terms:
        lesson_type_labels = {
            "concept": "공식 개념",
            "calculation": "계산 대상",
            "comparison": "비교 대상",
            "analysis": "분석 대상",
            "interpretation": "해석 대상",
            "implementation": "실행 대상",
            "exam-strategy": "판별 대상",
        }
        terms.append(lesson_type_labels.get(context.lesson_type, "공식 수행대상"))
    lesson_profile = action_profile_for(context, context.group_title)
    selected = _unique(terms)[:6]
    selected.extend((ACTION_LABELS[profile.code], ACTION_LABELS[lesson_profile.code]))
    return "·".join(_unique(selected))


