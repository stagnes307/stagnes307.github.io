def _field_score(text: str, keyword: str, weight: float) -> float:
    if not _keyword_matches(text, keyword):
        return 0.0
    return weight + min(len(keyword), 12) / 20


def _keyword_matches(text: str, keyword: str) -> bool:
    lowered = text.lower()
    target = keyword.lower()
    if target == "전기":
        return re.search(r"(?<![가-힣])전기", lowered) is not None
    if target == "환기":
        return target in lowered.replace("열교환기", "")
    if target in {"li", "cp"}:
        return re.search(rf"(?<![a-z]){re.escape(target)}(?![a-z])", lowered) is not None
    return target in lowered


def classify_topic(context: LessonContext, topic: str) -> KnowledgeGuide:
    """Select a guide using every curriculum path and source-ref field."""
    is_safety = context.course_id.startswith("industrial-safety")
    guides = (
        SAFETY_SPECIAL_GUIDES + SAFETY_GUIDES
        if is_safety
        else (TAGUCHI_GUIDE,) + QUALITY_SPECIAL_GUIDES + QUALITY_GUIDES
    )
    by_code = {guide.code: guide for guide in guides}
    route = " ".join((context.section_title, context.unit_title, context.group_title))
    if not is_safety:
        if context.group_title == "3정5S 활동하기":
            return by_code["workplace-organization-5s"]
        if context.group_title == "눈으로 보는 관리하기":
            return by_code["visual-management"]
        if "계수값 데이터" in topic:
            return by_code["doe-attribute"]
        if topic.strip() == "확률" or any(
            marker in topic for marker in ("모수와 통계량", "확률분포", "확률변수")
        ):
            return by_code["probability-distribution"]
        if "다구찌" in topic or "다구찌" in context.group_title:
            return TAGUCHI_GUIDE
        if "품질특성 및 설계변수" in context.group_title:
            return TAGUCHI_GUIDE
    # A specific term in the atom itself must not be shadowed by several broad
    # words repeated in its section/path.  Topic-local matches therefore decide
    # first; the full-context score is the fallback for generic practical atoms.
    topic_ranked = []
    for priority, guide in enumerate(guides):
        matched = [keyword for keyword in guide.keywords if _keyword_matches(topic, keyword)]
        topic_ranked.append((
            sum(10 + min(len(keyword), 16) for keyword in matched),
            max((len(keyword) for keyword in matched), default=0),
            -priority,
            guide,
        ))
    topic_score, _length, _priority, topic_guide = max(topic_ranked, key=lambda item: item[:3])

    if not is_safety:
        specialized = [
            item for item in topic_ranked
            if item[3] in QUALITY_SPECIAL_GUIDES and item[0] > 0
        ]
        if specialized:
            return max(specialized, key=lambda item: item[:3])[3]

    if is_safety:
        risk_path = " ".join((context.unit_title, context.group_title))
        mixed_electrical = "정전기" in topic and any(
            marker in topic for marker in ("과전류", "단락", "누전", "감전", "차단기")
        )
        static_route = "정전기" in risk_path or "정전기" in topic or "대전전압" in topic

        if any(marker in topic for marker in ("유해위험기계기구", "유해·위험기계기구")):
            return by_code["machinery"]
        if "안전보건표지" in topic:
            return by_code["management-emergency"]
        if "산업재해예방" in topic:
            return by_code["management-emergency"]
        if (
            "비상" in risk_path
            and any(marker in topic for marker in ("비상대응", "비상조치", "자체매뉴얼"))
        ):
            return by_code["management-emergency"]
        if "기계작업" in route and "작업환경" in topic:
            return by_code["machinery"]
        if (
            "건설" in route
            and any(marker in topic for marker in ("공사장 주변", "공법", "건설공사 특수성"))
        ):
            return by_code["construction"]
        if "화학공장" in topic and "위험등급" in topic:
            return by_code["fire-chemical"]
        if (
            "충전전로 근접" in context.group_title
            and any(marker in topic for marker in ("크레인", "중기작업", "중장비"))
        ):
            return by_code["electrical-proximity"]

        # Canonical topic-local formulas and official-law anchors win before a
        # broad section name.  This prevents, for example, accident statistics
        # in a machinery section from receiving a rotating-machine example.
        specific_codes = {
            "explosion-limits", "legal", "fire-chemical",
            "occupational-hygiene-agents", "work-sampling",
            "thermal-environment", "electrical-explosion",
            "electrical-proximity", "risk-assessment-administration",
            "niosh-lifting", "lifting-sling",
            "system-risk", "risk-additive", "risk-scoring",
            "accident-metrics", "accident-loss", "electric-shock",
            "safety-work-study", "human-physiology", "work-environment",
            "msd-assessment",
        }
        specific = [item for item in topic_ranked if item[3].code in specific_codes and item[0] > 0]
        if specific:
            selected = max(specific, key=lambda item: item[:3])[3]
            if selected.code == "electric-shock" and static_route and not mixed_electrical:
                return by_code["static"]
            return selected
        if "산업재해 대응" in context.unit_title:
            return by_code["management-emergency"]
        risk_route = any(marker in risk_path for marker in (
            "위험성평가", "위험성 평가", "위험성 파악·결정",
            "위험성 감소", "위험성 추정", "건설공사 위험성",
        ))
        risk_exact = any(marker in topic for marker in (
            "위험성평가", "위험성 평가", "위험성 추정",
        ))
        # An atom explicitly named risk assessment remains risk assessment even
        # when it sits under a chemical-safety inspection path.
        if risk_exact:
            return by_code["risk"]
        if "화공안전점검" in context.unit_title or "화공 안전운전" in context.unit_title:
            return by_code["chemical-inspection"]
        if topic_guide.code == "safety-inspection" and topic_score > 0:
            return SAFETY_INSPECTION_GUIDE
        if static_route and not mixed_electrical:
            return by_code["static"]
        if "전기" in route or "감전재해" in route or "절연용" in route:
            return by_code["electrical"]
        if risk_route:
            return by_code["risk"]
        if "인간공학" in context.section_title or "작업환경 관리" in context.unit_title:
            human_candidates = [
                item for item in topic_ranked
                if item[3] in (
                    MANUAL_LIFTING_GUIDE, SAFETY_WORK_STUDY_GUIDE,
                    MSD_ASSESSMENT_GUIDE, HUMAN_PHYSIOLOGY_GUIDE,
                    WORK_ENVIRONMENT_GUIDE, HUMAN_FACTORS_GUIDE,
                ) and item[0] > 0
            ]
            if human_candidates:
                return max(human_candidates, key=lambda item: item[:3])[3]
            return HUMAN_FACTORS_GUIDE
        if "사업장 안전점검" in context.unit_title:
            return SAFETY_INSPECTION_GUIDE
        if topic_guide.code == "lifting" and topic_score > 0:
            return topic_guide
        if "기계" in route and "전기" not in route:
            return by_code["machinery"]
        if "건설" in route:
            return by_code["construction"]

    if topic_score > 0:
        return topic_guide

    fields = (
        (topic, 9.0),
        (context.title, 5.0),
        (context.group_title, 4.0),
        (context.unit_title, 3.0),
        (context.section_title, 2.0),
        (" ".join(context.normalized_official_basis), 1.5),
        (" ".join(context.source_refs), 0.25),
        (" ".join(str(source.get("title", "")) for source in context.sources), 0.25),
    )
    ranked = []
    for priority, guide in enumerate(guides):
        score = sum(
            _field_score(field, keyword, weight)
            for field, weight in fields
            for keyword in guide.keywords
        )
        ranked.append((score, -priority, guide))
    score, _priority, guide = max(ranked, key=lambda item: (item[0], item[1]))
    if score >= 3.0:
        return guide
    return DEFAULT_SAFETY if context.course_id.startswith("industrial-safety") else DEFAULT_QUALITY


def guides_for_context(context: LessonContext) -> tuple[KnowledgeGuide, ...]:
    return tuple(classify_topic(context, topic) for topic in context.topics)


def _clause(value: str) -> str:
    return " ".join(value.split()).rstrip(".!?。！？")


def _sentence(value: str, question: bool = False) -> str:
    return _clause(value) + ("?" if question else ".")


def _basis(context: LessonContext, *, raw: bool = False) -> str:
    values = context.official_basis if raw else context.normalized_official_basis
    if values:
        return " / ".join(values)
    return f"{context.section_title} > {context.unit_title} > {context.group_title}"


def _sources(context: LessonContext) -> str:
    # Source titles can legitimately contain sentence punctuation, for example
    # ``[시행 2026. 3. 2.]``.  The H3 density counter therefore uses stable
    # source ids and ISO retrieval dates; the untouched title remains in the
    # provenance block rendered by ``_intro``.
    return " · ".join(
        f"{ref} 확인일 {source.get('retrieved_at', '미기록')}"
        for ref, source in zip(context.source_refs, context.sources)
    )


